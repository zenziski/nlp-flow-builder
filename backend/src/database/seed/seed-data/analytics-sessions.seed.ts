// ─── Public export ────────────────────────────────────────────────────────────

export function generateAnalyticsSessions(
  botId: Types.ObjectId,
  flowId: Types.ObjectId,
): object[] {
  const specs = buildSessions(botId, flowId);
  const now = new Date();

  return specs.map((spec) => {
    const lastTurn = spec.history[spec.history.length - 1];
    const lastActivityAt = lastTurn?.timestamp ?? spec.createdAt;

    const triggeredIntents =
      spec.intent !== 'fallback'
        ? [{ intent: spec.intent, score: spec.intentScore, timestamp: spec.createdAt }]
        : [];

    return {
      botId,
      flowId,
      userId: spec.userId,
      status: spec.status,
      isSimulator: false,
      history: spec.history,
      triggeredIntents,
      variables: spec.variables ?? {},
      context: {},
      currentNodeId: lastTurn?.nodeId ?? null,
      lastActivityAt,
      createdAt: spec.createdAt,
      updatedAt: now,
    };
  });
}
