// ─── Helpers ─────────────────────────────────────────────────────────────────

function d(year: number, month: number, day: number, hour: number, min = 0): Date {
  return new Date(year, month - 1, day, hour, min, 0);
}

function turn(
  role: 'user' | 'bot',
  content: string,
  base: Date,
  offsetSec: number,
  nodeId?: string,
) {
  return { role, content, timestamp: new Date(base.getTime() + offsetSec * 1000), nodeId };
}

